`timescale 1ns / 1ps

//============================================================
// Project : FlexRISC16 Pipeline
// Module  : Hazard Detection Unit
//============================================================

module hazard_detection_unit
(
    //--------------------------------------------------------
    // IF/ID Stage
    //--------------------------------------------------------

    input wire [3:0] if_id_rs1,
    input wire [3:0] if_id_rs2,

    //--------------------------------------------------------
    // ID/EX Stage
    //--------------------------------------------------------

    input wire id_ex_mem_read,

    input wire [3:0] id_ex_rd,

    //--------------------------------------------------------
    // Outputs
    //--------------------------------------------------------

    output reg stall_pc,
    output reg stall_if_id,
    output reg flush_id_ex

);

//============================================================
// Hazard Detection
//============================================================

always @(*)
begin

    //--------------------------------------------------------
    // Default
    //--------------------------------------------------------

    stall_pc   = 1'b0;

    stall_if_id = 1'b0;

    flush_id_ex = 1'b0;

    //--------------------------------------------------------
    // Load Use Hazard
    //--------------------------------------------------------

    if(id_ex_mem_read)

    begin

        if((id_ex_rd==if_id_rs1 && id_ex_rd!=0) ||

           (id_ex_rd==if_id_rs2 && id_ex_rd!=0))

        begin

            stall_pc    = 1'b1;

            stall_if_id = 1'b1;

            flush_id_ex = 1'b1;

        end

    end

end

endmodule